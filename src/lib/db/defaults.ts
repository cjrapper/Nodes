/**
 * 播种用的默认文本（人设 L0 / 工作区约定 L1）。
 *
 * ## 为什么单独一个文件
 *
 * 设置界面上的「恢复默认」按钮需要拿到**同一份**文本 —— 如果 UI 里再抄一遍，
 * "默认"就有了两个版本，用户点了恢复反而得到一段谁都没见过的内容。
 *
 * 但 UI 不能从 `lib/db/index.ts` 导入：那个模块会拉起 `better-sqlite3` 与
 * `node:crypto`，把它拖进客户端组件会让打包直接失败。所以默认文本必须住在
 * 一个**没有任何依赖**的模块里，服务端（播种）与客户端（恢复默认）共用它。
 *
 * ⚠️ 改动这里的文本会让**所有会话**的 L0 之后整段缓存失效一次。
 * 这是刻意的取舍：人设是"这个助手是谁"，写得不合适就该改，
 * 不该为了缓存命中率把系统提示冻结在一个不称职的版本上（见 AGENTS.md 第五节）。
 */

