/** CJK 统一表意文字（含扩展 A 与兼容区） */
const CJK = /[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]/g;

/** 判定为损坏所需的最少"非常用中文字"数量 —— 防一行里只有一两个生僻字时误报 */
const MIN_UNCOMMON = 3;

/**
 * 非常用字占比阈值。
 *
 * 这个数字是**量出来的**，不是拍的。实测：
 *
 * | 情况 | 非常用字占比 |
 * | --- | --- |
 * | 真损坏（Markdown 标题 / 日志模板 / 代码行） | **1.000** |
 * | 合法生僻词（饕餮、貔貅） | 0.222 |
 * | 合法生僻字（弩） | 0.118 |
 * | 正常技术中文 | 0.100 |
 *
 * 真损坏与合法文本之间差着一个数量级，所以取 0.5：离两边都有一倍以上余量。
 * 早期版本取 0.2，结果"## 常用字表里没有但确实合法的词：饕餮、貔貅"
 * 这种正常行被判成损坏 —— **假失败比假通过更危险**，因为它会让
 * `npm run verify` 永远失败，人于是学会忽略这个检查。
 */
const UNCOMMON_RATIO = 0.5;

export interface LineVerdict {
  corrupted: boolean;
  /** 该行中文字符总数 */
  cjkCount: number;
  /** 其中非常用字的数量 */
  uncommonCount: number;
  /** 非常用字占比 */
  ratio: number;
}

/** 分析一行，给出判据所需的全部数字（便于测试与排查） */
export function analyzeLine(line: string): LineVerdict {
  const cjk = line.match(CJK) ?? [];
  let uncommon = 0;
  for (const ch of cjk) {
    if (!COMMON_CHARS.has(ch)) uncommon += 1;
  }
  const ratio = cjk.length === 0 ? 0 : uncommon / cjk.length;
  return {
    corrupted: uncommon >= MIN_UNCOMMON && ratio > UNCOMMON_RATIO,
    cjkCount: cjk.length,
    uncommonCount: uncommon,
    ratio,
  };
}

/** 这一行是否像被错误编码写坏了 */
export function looksCorrupted(line: string): boolean {
  return analyzeLine(line).corrupted;
}

/**
 * 文件级豁免标记。
 *
 * ## 为什么必须有
 *
 * 有些文件**必须**包含真实的乱码文本 —— 最典型的是编码检查器自己的测试：
 * 它要验证"真损坏能被抓到"，那就得把真实的错误编码结果写进用例里。
 * 这类文件与"真的坏了"的文件在字节层面完全一样，无法靠内容区分。
 *
 * 所以给一条显式的豁免通道。放在文件任意位置即可（通常紧挨着那几行示例），
 * 但**必须写明理由** —— 豁免是知情的例外，不是让检查闭嘴的开关。
 *
 * 刻意不做"行级豁免"：那会让人习惯性地给报警行打标记，
 * 而真损坏恰恰也是成片出现的，行级豁免会让它更容易被掩盖。
 */
const IGNORE_MARKER = "encoding-check:ignore-file";

/** 这份文本是否声明了豁免 */
export function isIgnored(text: string): boolean {
  return text.includes(IGNORE_MARKER);
}

/** 扫描一段文本，返回疑似损坏的行号（1 起）；带豁免标记时返回空数组 */
export function findCorruptedLines(text: string): number[] {
  if (isIgnored(text)) return [];
  const bad: number[] = [];
  text.split("\n").forEach((line, index) => {
    if (looksCorrupted(line)) bad.push(index + 1);
  });
  return bad;
}
