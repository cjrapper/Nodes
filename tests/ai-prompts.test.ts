/**
 * 模块 AI 任务提示词的契约测试。
 *
 * ## 为什么单独测提示词
 *
 * 这两条 prompt 是产品的核心资产（用户点了按钮就直接用它），
 * 而且它们的措辞里藏着一个**曾经真实存在的设计缺陷**。
 *
 * ## 那个缺陷
 *
 * 原提示词的第一条严格约束是：
 *
 * > 只依据我实际挂载的内容判断。不要假设我写过任何没有出现在上下文里的主题。
 *
 * 它的**意图**是对的：防止模型编造用户没写过的知识点，让用户误以为自己整理过。
 * 但它的**作用域太宽** —— 把"判断我的笔记"和"判断这个领域"混为一谈，
 * 于是「缺什么主题」「市场怎么看」「换个场景还成不成立」这些问题
 * **全部被自己的提示词禁掉了**。
 *
 * 而这恰恰是用户最需要 AI 的部分：他没有行业经验，
 * 问不出自己想不到的角度（他自己也明确说了这个反身困境）。
 * 一个被要求"只依据挂载内容"的助手只会把他的盲区原样反射回去。
 *
 * ## 正确的划界
 *
 * | | 规则 |
 * | --- | --- |
 * | 事实**归属** | 严格 —— 不许把我没写过的东西说成我写过了 |
 * | 分析**维度** | 开放 —— 该用行业经验就用，缺口的答案本来就在笔记之外 |
 *
 * 下面的断言就是钉住这条界线：两个方向都要守 ——
 * 既不能被"开放"冲掉归属的严格性，也不能被"严格"压掉维度的开放性。
 */

import assert from "node:assert/strict";
import { test } from "node:test";

import { MODULE_AI_ACTIONS } from "../src/components/module-overview.tsx";

function promptOf(kind: string): string {
  const action = MODULE_AI_ACTIONS.find((a) => a.kind === kind);
  assert.ok(action, `找不到 AI 任务：${kind}`);
  return action.prompt;
}

/* ------------------------------------------------------------------ *
 * 1. 归属要严格（原意图，不能丢）
 * ------------------------------------------------------------------ */

test("两条提示词都要求：不许把我没写过的说成我写过了", () => {
  for (const kind of ["gap", "quiz"]) {
    const prompt = promptOf(kind);
    assert.match(
      prompt,
      /不要(说|考)我(写过|没写过)|只考我挂载|只依据/,
      `${kind} 必须保留"事实归属严格"这条 —— 否则模型会编出用户根本没写过的知识点`,
    );
  }
});

test("AI 分析要求：说得出对应哪一篇，说不出就不要提", () => {
  assert.match(promptOf("gap"), /说得出它对应哪一篇|说不出就不要提/);
});

/* ------------------------------------------------------------------ *
 * 2. 维度要开放（本次修复的核心）
 * ------------------------------------------------------------------ */

test("AI 分析不得再写「只依据我实际挂载的内容判断」这种过宽约束", () => {
  /*
   * 这条是本次修复的核心断言。
   *
   * "只依据挂载内容判断"把两个不同的问题混成了一个：
   *  - 我写了什么？（只能从挂载内容判断 —— 对）
   *  - 这个方向该有什么？（必须用行业经验 —— 被这句话禁掉了）
   *
   * 第二种问题的答案**必然在笔记之外**，所以任何"判断只依据挂载内容"
   * 的措辞都会让「查漏补缺」和「多角度分析」无法工作。
   */
  const prompt = promptOf("gap");
  assert.doesNotMatch(
    prompt,
    /只依据我实际挂载的内容判断/,
    "不能要求「判断」都只依据挂载内容 —— 缺口与行业判断需要笔记之外的信息",
  );
});

test("AI 分析明确授权使用行业经验与领域知识", () => {
  const prompt = promptOf("gap");
  assert.match(prompt, /行业经验|领域知识/, "必须显式授权它用行业经验");
  assert.match(
    prompt,
    /笔记之外|本来就在我的|正是我找你/,
    "要说明缺口的答案本来就在笔记之外 —— 否则模型仍会自我审查",
  );
});

test("AI 分析要求区分「我笔记里的」与「你的判断」", () => {
  // 开放维度的前提是来源可核对，否则用户分不清哪句是自己的笔记
  assert.match(promptOf("gap"), /分开|分清/, "必须要求区分来源");
});

/* ------------------------------------------------------------------ *
 * 3. 多角度分析：用户的核心诉求
 * ------------------------------------------------------------------ */

test("AI 分析必须有专门一节讲「我没想到要问的」", () => {
  const prompt = promptOf("gap");
  assert.match(prompt, /我没想到要问的|没想到/, "必须有这一节 —— 这是对用户盲区的正面回应");
  assert.match(prompt, /视野窄|盲区/, "要点明用户的风险是视野窄");
});

test("AI 分析的多角度至少覆盖场景、商业市场、玩家体验、工程现实", () => {
  const prompt = promptOf("gap");
  for (const angle of ["场景", "商业与市场", "玩家", "工程"]) {
    assert.ok(prompt.includes(angle), `AI 分析缺少分析角度：${angle}`);
  }
});

test("AI 分析要求给出场景维度上的具体分岔（换前提结论会不会反过来）", () => {
  const prompt = promptOf("gap");
  assert.match(prompt, /手游|主机|3A|独立/, "要举出具体场景，而不是抽象地说「注意场景」");
  assert.match(prompt, /商业与市场层面/, "要把商业与市场明确写成必须覆盖的维度");
});

/* ------------------------------------------------------------------ *
 * 4. 出题任务：范围受限，但答案不受限
 * ------------------------------------------------------------------ */

test("自测提问限制的是「考什么」，不是「答案能从哪来」", () => {
  const prompt = promptOf("quiz");
  assert.match(prompt, /出题范围/, "要明确约束的是出题范围");
  assert.match(
    prompt,
    /这只约束|都请充分用你的行业经验/,
    "必须说明参考答案与判断标准不受笔记限制 —— 否则答案会退化成复述笔记",
  );
});

test("自测提问必须至少有一道题把技术选择放进真实项目约束", () => {
  const prompt = promptOf("quiz");
  assert.match(prompt, /真实项目约束/, "这是用户完全没有经验、最容易答成技术报告的一类题");
  assert.match(prompt, /成本|周期|发行平台|目标用户/, "要举出具体的约束类型");
});

/* ------------------------------------------------------------------ *
 * 5. 不应该重复人设里已经定义过的东西
 * ------------------------------------------------------------------ */

test("两条提示词都不再自带角色定义（人设已经在 L0 说明身份）", () => {
  /*
   * L0 已经定义了"你是谁"。任务提示词里再写一遍角色，会出现两个问题：
   *  1. 两处说法不一致时互相稀释（L0 的教训，见 DESIGN.md 2.10）；
   *  2. 那句角色后面往往跟着"只依据挂载内容"这类约束，
   *     容易把身份约束和分析范围约束绑在一起 —— 正是之前的病根。
   */
  for (const kind of ["gap", "prep", "quiz"]) {
    const prompt = promptOf(kind);
    assert.doesNotMatch(
      prompt,
      /^你是一位/,
      `${kind} 不应以角色定义开头 —— 身份由人设（L0）统一负责`,
    );
  }
});

/* ------------------------------------------------------------------ *
 * 6. 秋招处境必须贯穿到任务提示词里
 *
 * 人设（L0）说明了"我正在秋招"，但任务提示词如果还是"帮我做一次完整的
 * 知识库体检"，模型就会按体检的形态输出 —— 一份平铺的优劣清单。
 *
 * 这是**真实发生过的问题**：用户的原话是「这个规则设置不对，
 * 他是游戏行业的指导导师，我现在在忙于秋招」。
 * 那一版提示词里甚至写着"如果只剩一周"——用假设语气谈一件正在发生的事。
 * ------------------------------------------------------------------ */

test("每个动作都点明秋招处境", () => {
  for (const kind of ["gap", "prep", "quiz"]) {
    assert.match(
      promptOf(kind),
      /秋招|面试/,
      `${kind} 要落在求职场景里 —— 脱离了"正在秋招"这个前提，它给的就是通用建议`,
    );
  }
});

test("AI 分析不再用「如果只剩一周」这种假设语气", () => {
  /*
   * 那条措辞暴露了整个提示词的错位：它把秋招当成"将来可能发生的事"，
   * 于是输出按"学习规划"组织，而用户需要的是"这周该干什么"。
   */
  assert.doesNotMatch(
    promptOf("gap"),
    /如果只剩一周/,
    "秋招正在进行，不该用假设语气 —— 改成直接给时间分配",
  );
  assert.match(promptOf("gap"), /时间分配|该放掉什么/, "要直接给取舍，而不是假设性的推演");
});

test("AI 分析的第二部分问的是「会被怎么考」，不是「还缺什么知识点」", () => {
  /*
   * 原版第二部分是「明显缺失的主题」，暗示用户该去补新主题。
   * 而秋招期补新主题的边际收益通常低于把已有的练到能讲清 ——
   * 一份"你还缺这 8 个主题"的清单会把人带偏。
   */
  const prompt = promptOf("gap");
  assert.match(prompt, /面试官会怎么考|最可能被问到/, "要转向面试实战视角");
  assert.match(prompt, /答到什么程度算过关/, "要给判定标准，而不只是知识清单");
  assert.match(prompt, /主动展示|不要主动提/, "要覆盖「该往哪引／该避开什么」这类实战取舍");
});

test("AI 分析要求每条建议都带时间账", () => {
  assert.match(
    promptOf("gap"),
    /时间账/,
    "没有时间账的建议对秋招期的人等于帮倒忙 —— 这是人设里的硬约束，提示词要跟上",
  );
});

test("AI 分析允许它说「这块可以了，别再投入」", () => {
  /*
   * 只给"还缺什么"的评估会让人永远停不下来 —— 用户明确说需要知道
   * 什么时候可以停。这一条是"助手"和"焦虑制造机"的分界线。
   */
  assert.match(
    promptOf("gap"),
    /可以了|别再投入|什么时候可以停/,
    "必须允许它给出「停止」的结论，否则用户会一直打磨同一块",
  );
});

/* ------------------------------------------------------------------ *
 * 7. 岗前准备 —— 秋招期独有的动作
 * ------------------------------------------------------------------ */

test("存在「岗前准备」动作，且它要用户粘 JD", () => {
  const prompt = promptOf("prep");
  assert.match(prompt, /JD/, "要基于真实岗位 JD，而不是泛泛准备");
  assert.match(prompt, /粘贴/, "要给出粘贴位置");
});

test("岗前准备要求：没粘 JD 就先问，不许凭空猜岗位", () => {
  // 凭空的岗位画像会给出看似专业、实际没法用的建议
  assert.match(promptOf("prep"), /先问我 JD|不要凭空猜/, "缺输入时要先问，而不是编一个岗位出来");
});

test("岗前准备覆盖转行者最实际的三件事", () => {
  const prompt = promptOf("prep");
  assert.match(prompt, /项目经历该怎么讲|不是游戏项目/, "转行者的项目经历怎么包装是核心痛点");
  assert.match(prompt, /不要硬吹|吹了会被追问到塌/, "同时要给包装的边界，否则等于教人作假");
  assert.match(prompt, /我该反问什么|反问/, "反问环节是面试的一部分，且多数人完全没准备");
  assert.match(prompt, /最可能挂在哪里/, "要说清风险，而不是只给鼓励");
});

test("岗前准备要区分「必修 / 可以坦白说不会 / 其实用不上」三档", () => {
  /*
   * 把"岗位要但我没有"的东西混成一个待办清单，会让人在面试前疯狂补一堆
   * 补不完的东西，反而把能讲好的部分也搞乱了。
   * 分档之后才有取舍：第一档必做，第二档想好话术，第三档直接放弃。
   */
  assert.match(promptOf("prep"), /必修.*坦白说不会.*用不上/s, "要分三档，而不是一个清单");
});
